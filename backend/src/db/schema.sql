-- Moodloom schema.
--
-- This file is idempotent: `npm run migrate` runs all of it every time, so
-- every statement must be safe on both an empty database and one that is
-- already up to date (CREATE ... IF NOT EXISTS, ADD COLUMN IF NOT EXISTS).
-- New columns go in as ALTERs below their table so an older database picks
-- them up without a separate migration step.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ───────────────────────── accounts ─────────────────────────

-- Auth model: anonymous by default, optionally claimed with email + password.
CREATE TABLE IF NOT EXISTS users (
  id SERIAL PRIMARY KEY,
  anon_token UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  email TEXT UNIQUE,
  password_hash TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Bumped to invalidate every token already issued for the account (password
-- change, password reset, "sign out everywhere"). Each JWT carries the value
-- it was signed with; a mismatch is a 401.
ALTER TABLE users ADD COLUMN IF NOT EXISTS token_version INTEGER NOT NULL DEFAULT 0;
-- 'free' or 'pro'. Limits live in services/plans.js and are only enforced
-- when ENFORCE_PLAN_LIMITS is on.
ALTER TABLE users ADD COLUMN IF NOT EXISTS plan TEXT NOT NULL DEFAULT 'free';
ALTER TABLE users ADD COLUMN IF NOT EXISTS display_name TEXT;

-- Short-lived codes for pairing the browser extension to the SAME account the
-- web app is using. Generated by the (signed-in) web app, redeemed once.
CREATE TABLE IF NOT EXISTS pairing_codes (
  code TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Single-use, expiring password-reset tokens. Only a SHA-256 hash is stored
-- (the raw token exists only in the emailed link).
CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id SERIAL PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_user_id ON password_reset_tokens(user_id);

-- Metered actions (currently: AI direction notes), for monthly plan limits.
CREATE TABLE IF NOT EXISTS usage_events (
  id BIGSERIAL PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_usage_events_user_kind ON usage_events(user_id, kind, created_at);

-- ───────────────────────── projects ─────────────────────────

CREATE TABLE IF NOT EXISTS projects (
  id SERIAL PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_projects_user_id ON projects(user_id);

-- The written brief (client, audience, goals, constraints, keywords…) and
-- where the project is in its process. Free-form JSON, validated in the API.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS brief JSONB NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE projects ADD COLUMN IF NOT EXISTS stage TEXT NOT NULL DEFAULT 'brief';
-- Consent switch: nothing from this project is sent to a third-party AI
-- service unless the owner has turned this on.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS ai_enabled BOOLEAN NOT NULL DEFAULT false;

-- People other than the owner who can open a project. The owner is always
-- projects.user_id and never has a row here.
CREATE TABLE IF NOT EXISTS project_members (
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('editor', 'viewer')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_project_members_user ON project_members(user_id);

-- Invitation links to join a project as a member. Hash only, single use.
CREATE TABLE IF NOT EXISTS project_invites (
  id SERIAL PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  role TEXT NOT NULL CHECK (role IN ('editor', 'viewer')),
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_project_invites_project ON project_invites(project_id);

-- Read-only public links (for showing a client a board or brand kit without
-- an account). The token is stored as-is so the owner can copy the link
-- again later; revoking deletes the row.
CREATE TABLE IF NOT EXISTS share_links (
  id SERIAL PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  token TEXT NOT NULL UNIQUE,
  include_board BOOLEAN NOT NULL DEFAULT true,
  include_notes BOOLEAN NOT NULL DEFAULT false,
  include_brand BOOLEAN NOT NULL DEFAULT false,
  include_brief BOOLEAN NOT NULL DEFAULT false,
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_share_links_project ON share_links(project_id);

-- ───────────────────────── board ─────────────────────────

-- User-defined groupings within a project. Per project, fully editable.
CREATE TABLE IF NOT EXISTS categories (
  id SERIAL PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  position INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_categories_project_id ON categories(project_id);

-- Every reference on a project's board.
CREATE TABLE IF NOT EXISTS board_items (
  id SERIAL PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  source_url TEXT NOT NULL,
  media_type TEXT NOT NULL,
  title TEXT,
  thumbnail_url TEXT,
  embed_html TEXT,
  position INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- NULL = uncategorized. Removing a category un-categorizes its items.
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL;

-- Why it was saved, in the designer's own words, plus free tags.
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS note TEXT;
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS tags TEXT[] NOT NULL DEFAULT '{}';
-- Pixel size of the preview, so the board can reserve the right space before
-- the image loads; and the extracted colour palette ([{hex, pct, name}]).
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS width INTEGER;
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS height INTEGER;
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS palette JSONB;
-- Type-specific extras: {provider, videoId} for embeds, {fromItemId, page}
-- for a quote lifted from a PDF, {traits: [...]} computed colour character.
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS meta JSONB NOT NULL DEFAULT '{}'::jsonb;
-- Set when Moodloom itself stores the bytes (an upload). storage_key is the
-- file's name inside the uploads directory; the public URL is derived from
-- it at response time so stored data survives a change of domain.
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS storage_key TEXT;
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS thumb_key TEXT;
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS file_name TEXT;
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS file_size BIGINT;
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS mime_type TEXT;
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS analyzed_at TIMESTAMPTZ;
ALTER TABLE board_items ADD COLUMN IF NOT EXISTS created_by INTEGER REFERENCES users(id) ON DELETE SET NULL;

-- The set of kinds has grown since v1 (image, video, link); replace the
-- original inline CHECK with a named one that can be extended again.
ALTER TABLE board_items DROP CONSTRAINT IF EXISTS board_items_media_type_check;
ALTER TABLE board_items ADD CONSTRAINT board_items_media_type_check
  CHECK (media_type IN ('image', 'video', 'link', 'pdf', 'font', 'file', 'quote'));

CREATE INDEX IF NOT EXISTS idx_board_items_project_id ON board_items(project_id);
CREATE INDEX IF NOT EXISTS idx_board_items_category_id ON board_items(category_id);
CREATE INDEX IF NOT EXISTS idx_board_items_tags ON board_items USING GIN (tags);

-- Backstop for the duplicate-capture guard: the same URL cannot be on one
-- board twice, whatever the timing of two requests.
CREATE UNIQUE INDEX IF NOT EXISTS idx_board_items_project_url_unique
  ON board_items(project_id, source_url);

-- One feature vector per item, for "more like this" and grouping. `model`
-- records which embedder produced it; vectors from different models are
-- never compared with each other.
CREATE TABLE IF NOT EXISTS item_embeddings (
  item_id INTEGER PRIMARY KEY REFERENCES board_items(id) ON DELETE CASCADE,
  model TEXT NOT NULL,
  vector REAL[] NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ───────────────────────── workspace ─────────────────────────

-- Rich-text notes (HTML produced by the editor), one per project.
CREATE TABLE IF NOT EXISTS workspace_notes (
  id SERIAL PRIMARY KEY,
  project_id INTEGER NOT NULL UNIQUE REFERENCES projects(id) ON DELETE CASCADE,
  content TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- The sketch canvas scene (Excalidraw JSON, stored as text), one per project.
CREATE TABLE IF NOT EXISTS canvases (
  project_id INTEGER PRIMARY KEY REFERENCES projects(id) ON DELETE CASCADE,
  scene TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- The brand kit document (colours, type, logos, voice, rules), one per project.
CREATE TABLE IF NOT EXISTS brand_kits (
  project_id INTEGER PRIMARY KEY REFERENCES projects(id) ON DELETE CASCADE,
  data JSONB NOT NULL DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Direction notes written by a language model from a set of references.
-- Kept with their provenance (model, prompt version, exactly which items
-- were sent) so any note can be traced back to its inputs.
CREATE TABLE IF NOT EXISTS direction_notes (
  id SERIAL PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
  content JSONB NOT NULL,
  model TEXT NOT NULL,
  prompt_version TEXT NOT NULL,
  source_item_ids INTEGER[] NOT NULL DEFAULT '{}',
  usage JSONB,
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_direction_notes_project ON direction_notes(project_id, created_at DESC);
