// Runs every offline experiment and writes the results to docs/ai/.
//   npm run ai:eval
// Needs no database, no network and no API key. Deterministic: the same
// code gives the same numbers (timings aside).
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';
import { runPaletteEval } from './eval/palette.js';
import { runSimilarityEval } from './eval/similarity.js';

const outDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'docs', 'ai');
fs.mkdirSync(outDir, { recursive: true });

console.log('Experiment 1: palette extraction…');
const palette = await runPaletteEval();
console.log('Experiments 2 and 3: similarity and selection…');
const similarity = await runSimilarityEval();

const results = {
  generatedAt: new Date().toISOString(),
  machine: `${os.cpus()[0]?.model || 'unknown CPU'}, ${os.cpus().length} cores, Node ${process.version}`,
  palette,
  similarity,
};
fs.writeFileSync(path.join(outDir, 'results.json'), JSON.stringify(results, null, 2) + '\n');

const table = (rows, columns) => {
  const head = `| ${columns.map((c) => c[0]).join(' | ')} |`;
  const rule = `| ${columns.map(() => '---').join(' | ')} |`;
  return [head, rule, ...rows.map((row) => `| ${columns.map((c) => row[c[1]]).join(' | ')} |`)].join('\n');
};

const md = [];
md.push('# Measured results', '');
md.push(`Generated by \`npm run ai:eval\` on ${results.generatedAt.slice(0, 10)} (${results.machine}).`, '');
md.push('All images here are synthetic, generated from a fixed seed with known ground truth. That makes the numbers exact and reproducible, and it is also their limit: they show the methods behave correctly on controlled input, not how they perform on real photographs and screenshots. See REPORT.md for what that does and does not establish.', '');
md.push('## 1. Palette extraction', '');
md.push('150 images per condition, each made of 2 to 5 colours at least ΔE00 22 apart, in known proportions.', '');
md.push('- **mean ΔE00**: colour error between each true colour and the closest extracted one (under 1 is invisible, 2 to 3 is noticeable side by side). Capped at 50 per colour.');
md.push('- **recall**: share of true colours recovered within ΔE00 5.');
md.push('- **share error**: for recovered colours, how far off the reported proportion is, in percentage points.');
md.push('- **extra colours**: how many swatches were returned beyond the true number.');
md.push('- **exact count**: share of images where the number of swatches equals the true number of colours.', '');
for (const condition of [...new Set(palette.map((p) => p.condition))]) {
  md.push(`### ${condition}`, '');
  md.push(table(palette.filter((p) => p.condition === condition), [
    ['method', 'method'], ['mean ΔE00', 'meanDeltaE'], ['recall', 'recall'], ['share error (pts)', 'shareErrorPts'], ['extra colours', 'extraColours'], ['exact count', 'exactCount'], ['ms / image', 'msPerImage'],
  ]), '');
}
md.push('## 2. Similarity (classic features)', '');
md.push(`${similarity.dataset.images} images in ${similarity.dataset.classes} classes (6 colour families x 6 structures, ${similarity.dataset.perClass} each). Each image is used as a query against all the others.`, '');
md.push('- **top-1**: the single nearest image is from the same class.');
md.push('- **P@5**: share of the five nearest that are from the same class.');
md.push('- **mAP**: mean average precision over the full ranking.', '');
for (const task of [...new Set(similarity.retrieval.map((r) => r.task))]) {
  md.push(`### ${task}`, '');
  md.push(table(similarity.retrieval.filter((r) => r.task === task), [['features', 'variant'], ['top-1', 'top1'], ['P@5', 'precisionAt5'], ['mAP', 'meanAP'], ['chance', 'chance']]), '');
}
md.push(`Vector size: ${similarity.timing.dims} numbers. Time per image on this machine: ${similarity.timing.decodeMsPerImage} ms to decode and resize, ${similarity.timing.featureMsPerImage} ms to compute the features.`, '');
md.push('## 3. Choosing which references a model sees', '');
md.push(`Choosing ${similarity.selection.choose} of ${similarity.selection.from} images. **coverage** is the mean distance from every image to its nearest chosen one (lower is better); **families** and **structures** are how many of the 6 of each appear among the chosen.`, '');
md.push(table(
  ['farthest-point (used)', 'random (mean of 300 draws)', 'first ten (a board added in order)'].map((k) => ({ method: k, ...similarity.selection[k] })),
  [['method', 'method'], ['coverage', 'coverage'], ['families (of 6)', 'families'], ['structures (of 6)', 'structures']]
), '');
fs.writeFileSync(path.join(outDir, 'RESULTS.md'), md.join('\n'));
console.log(`Wrote ${path.join(outDir, 'results.json')} and RESULTS.md`);
